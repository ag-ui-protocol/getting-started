/**
 * The C# emitter: wire model in, the AGUI.Protobuf mappers out.
 *
 * Emits the .NET translation layer between the AGUI.Abstractions models and
 * the protoc-generated C# types (Grpc.Tools compiles those from the same
 * .proto files at build time). The event mapper is field-driven from the wire
 * model; the tables in this file are .NET idiom — which model class carries a
 * definition, which property name deviates from PascalCase, where a model
 * keeps a non-nullable string with an empty default — never field meaning.
 *
 * Every event in the envelope maps to a model class, subagent events included.
 */

import type { Definition, Field, ObjectDefinition, TypeExpr } from "./ir";
import {
  NULLABLE_REQUIRED_ANY,
  NULLABLE_REQUIRED_STRINGS,
  PROP_NAME,
} from "./dotnet-idioms";
import { buildScanGraph } from "./protobuf";
import type { WireModel } from "./protobuf";

/* ------------------------------------------------------------------ */
/* .NET idiom tables                                                    */
/* ------------------------------------------------------------------ */

// PROP_NAME, NULLABLE_REQUIRED_STRINGS and NULLABLE_REQUIRED_ANY live in
// dotnet-idioms.ts: the model emitter declares those properties and these
// mappers carry them, so the two have to read one table rather than two copies
// that can drift apart — a divergence here produces exactly the bare
// ArgumentNullException the nullable-strings table exists to prevent.

/**
 * The union-valued event fields the wire flattens into sibling fields, each with
 * bespoke encode and decode below. A union field not named here has no mapping
 * at all, which is a generator gap rather than a shape the wire omits.
 */
const FLATTENED_UNION_FIELDS = new Set([
  "RunFinishedEvent.outcome",
  "SubagentFinishedEvent.outcome",
]);

function pascalCase(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

function propertyOf(definitionName: string, field: Field): string {
  return PROP_NAME[`${definitionName}.${field.name}`] ?? pascalCase(field.name);
}

function banner(schemaId: string): string {
  return [
    "// <auto-generated />",
    "// @generated by spec/generator — DO NOT EDIT.",
    `// Source: ${schemaId}`,
    "// Regenerate: pnpm --filter @ag-ui/spec generate",
    "#nullable enable",
  ].join("\n");
}

