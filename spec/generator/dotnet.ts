type Kind =
  | "requiredString"
  | "nullableRequiredString"
  | "optionalString"
  | "requiredInt"
  | "optionalInt"
  | "requiredBool"
  | "optionalBool"
  | "requiredAny"
  | "nullableRequiredAny"
  | "optionalAny"
  | "openMap"
  | "patchArray"
  | "messageArray"
  | "usageArray"
  | "interruptArray"
  | "stringArray"
  | "inputMessage"
  | "skip";

interface EventFieldPlan {
  field: Field;
  property: string;
  wireProperty: string;
  kind: Kind;
  /** Closed value set (literal / string enum), enforced on decode. */
  allowed?: string[];
}

function resolveAlias(defs: Map<string, Definition>, type: TypeExpr): TypeExpr {
  while (type.kind === "ref") {
    const target = defs.get(type.name);
    if (target?.kind !== "alias") return type;
    type = target.type;
  }
  return type;
}

/**
 * The closed value set of a literal or string-enum typed field. The wire
 * carries plain strings, so decode has to enforce the set itself — the
 * TypeScript validators reject out-of-set values and this runtime must too.
 */
function allowedValues(
  defs: Map<string, Definition>,
  field: Field,
): string[] | undefined {
  const resolved = resolveAlias(defs, field.type);
  if (resolved.kind === "literal") return [resolved.value];
  if (resolved.kind === "stringEnum") return resolved.values;
  if (resolved.kind === "ref") {
    const target = defs.get(resolved.name);
    if (target?.kind === "enum") return target.values;
  }
  return undefined;
}

function classify(
  defs: Map<string, Definition>,
  definitionName: string,
  field: Field,
): Kind {
  const key = `${definitionName}.${field.name}`;
  const resolved = resolveAlias(defs, field.type);
  switch (resolved.kind) {
    case "string":
    case "literal":
    case "stringEnum":
      if (field.required) {
        return NULLABLE_REQUIRED_STRINGS.has(key)
          ? "nullableRequiredString"
          : "requiredString";
      }
      return "optionalString";
    case "integer":
      return field.required ? "requiredInt" : "optionalInt";
    case "boolean":
      return field.required ? "requiredBool" : "optionalBool";
    case "any":
      if (!field.required) return "optionalAny";
      return NULLABLE_REQUIRED_ANY.has(key)
        ? "nullableRequiredAny"
        : "requiredAny";
    case "openMap":
      return "openMap";
    case "array": {
      const items =
        resolved.items.kind === "ref"
          ? defs.get(resolved.items.name)
          : undefined;
      if (items?.name === "JsonPatchOperation" || items?.name === "Message") {
        // Both encode by enumerating the model's list and decode by adding into
        // it, which a nullable property (an optional array) supports in neither
        // direction. No such field exists today; one would need the mappers
        // taught first.
        if (!field.required) {
          throw new Error(
            `${key} is an optional ${items.name} array, which the .NET protobuf ` +
              "mappers cannot carry — make it required or teach the mappers the " +
              "nullable form",
          );
        }
        return items.name === "Message" ? "messageArray" : "patchArray";
      }
      if (items?.name === "TokenUsage") {
        // AddUsage writes nothing for an absent list and BuildUsage answers an
        // empty repeated field with null, both of which a required list would
        // contradict. No such field exists today.
        if (field.required) {
          throw new Error(
            `${key} is a required TokenUsage array, which the .NET protobuf mappers ` +
              "read as absent-or-null — make it optional or teach the mappers the " +
              "required form",
          );
        }
        return "usageArray";
      }
      if (items?.name === "Interrupt") return "interruptArray";
      return "stringArray";
    }
    case "ref": {
      const target = defs.get(resolved.name);
      if (target?.kind === "enum") {
        // Enums ride the wire as strings.
        return field.required ? "requiredString" : "optionalString";
      }
      if (target?.name === "RunAgentInput") return "inputMessage";
      throw new Error(`no .NET mapping for ${key} -> ${resolved.name}`);
    }
    default:
      throw new Error(`no .NET mapping for ${key}`);
  }
}

function encodeField(
  plan: EventFieldPlan,
  proto: string,
  model: string,
  eventTypeConstant: string,
): string[] {
  const p = `${proto}.${plan.wireProperty}`;
  const m = `${model}.${plan.property}`;
  switch (plan.kind) {
    case "requiredString":
      return [`${p} = ${m};`];
    case "nullableRequiredString":
      return [
        `RequireProvided(${m}, "${plan.field.name}", ${eventTypeConstant});`,
        `${p} = ${m}!;`,
      ];
    case "optionalString":
      return [`if (${m} is not null)`, `{`, `    ${p} = ${m};`, `}`];
    case "requiredInt":
    case "requiredBool":
      return [`${p} = ${m};`];
    case "optionalInt":
    case "optionalBool":
      return [`if (${m}.HasValue)`, `{`, `    ${p} = ${m}.Value;`, `}`];
    case "requiredAny":
      return [`${p} = ProtoValueConverter.ToValue(${m});`];
    case "nullableRequiredAny":
      // Required on the wire: a C#-null model value still writes a JSON null,
      // so a decoder that insists on the field's presence (the TypeScript
      // validators do) can read it.
      return [
        `${p} = ${m} is null`,
        `    ? new Google.Protobuf.WellKnownTypes.Value { NullValue = Google.Protobuf.WellKnownTypes.NullValue.NullValue }`,
        `    : ProtoValueConverter.ToValue(${m}.Value);`,
      ];
    case "optionalAny":
      return [
        `if (${m} is not null)`,
        `{`,
        `    ${p} = ProtoValueConverter.ToValue(${m}.Value);`,
        `}`,
      ];
    case "openMap":
      return [`${p} = ProtoValueConverter.ToStructOrNull(${m});`];
    case "patchArray":
      return [
        `if (${m}.ValueKind == JsonValueKind.Array)`,
        `{`,
        `    foreach (var operation in ${m}.EnumerateArray())`,
        `    {`,
        `        ${p}.Add(ProtoMessageMapper.ToProtoPatchOperation(operation));`,
        `    }`,
        `}`,
      ];
    case "messageArray":
      return [
        `foreach (var message in ${m})`,
        `{`,
        `    ${p}.Add(ProtoMessageMapper.ToProto(message));`,
        `}`,
      ];
    case "usageArray":
      return [`AddUsage(${p}, ${m});`];
    case "inputMessage":
      return [
        `if (${m} is not null)`,
        `{`,
        `    ${p} = ProtoMessageMapper.ToProtoRunAgentInput(${m});`,
        `}`,
      ];
    case "skip":
      return [];
    default:
      throw new Error(
        `encode: unhandled kind ${plan.kind} for ${plan.property} ` +
          `(the schema's ${plan.field.name})`,
      );
  }
}

function decodeField(plan: EventFieldPlan, proto: string): string | undefined {
  const p = `${proto}.${plan.wireProperty}`;
  // Literal / string-enum fields reject out-of-set wire values, matching the
  // TypeScript validators.
  const guarded = (value: string): string =>
    plan.allowed
      ? `AssertOneOf(${value}, "${plan.field.name}", ${plan.allowed
          .map((entry) => JSON.stringify(entry))
          .join(", ")})`
      : value;
  switch (plan.kind) {
    case "requiredString":
    case "nullableRequiredString":
      return `${plan.property} = ${guarded(p)},`;
    case "optionalString":
      return `${plan.property} = ${proto}.Has${plan.wireProperty} ? ${guarded(p)} : null,`;
    case "requiredInt":
    case "requiredBool":
      return `${plan.property} = ${p},`;
    case "optionalInt":
    case "optionalBool":
      return `${plan.property} = ${proto}.Has${plan.wireProperty} ? ${p} : null,`;
    case "requiredAny":
    case "nullableRequiredAny":
      // Required on the wire: an absent Value message is malformed (an
      // explicit JSON null rides as a non-null Value with null_value set).
      return `${plan.property} = ${p} is null ? throw MissingRequiredField("${plan.field.name}") : ProtoValueConverter.ToJsonElement(${p}),`;
    case "optionalAny":
      return `${plan.property} = ProtoValueConverter.ToJsonElementOrNull(${p}),`;
    case "openMap":
      // A required record must be present on the wire, as on the JSON path.
      return plan.field.required
        ? `${plan.property} = ProtoValueConverter.StructToJsonElementOrNull(${p}) ?? throw MissingRequiredField("${plan.field.name}"),`
        : `${plan.property} = ProtoValueConverter.StructToJsonElementOrNull(${p}),`;
    case "usageArray":
      return `${plan.property} = BuildUsage(${p}),`;
    case "inputMessage":
      return plan.field.required
        ? `${plan.property} = ${p} is null ? throw MissingRequiredField("${plan.field.name}") : ProtoMessageMapper.FromProtoRunAgentInput(${p}),`
        : `${plan.property} = ${p} is null ? null : ProtoMessageMapper.FromProtoRunAgentInput(${p}),`;
    case "skip":
      return undefined;
    // Not an initializer, but not unhandled either: both are decoded by the
    // loop that follows the object initializer, because a repeated field is
    // added into rather than assigned.
    case "messageArray":
    case "patchArray":
      return undefined;
    default:
      // Same as encodeField's default, deliberately: a kind only one half of
      // the pair knows about is a field that crosses the wire in one direction
      // and silently vanishes in the other.
      throw new Error(
        `decode: unhandled kind ${plan.kind} for ${plan.property} ` +
          `(the schema's ${plan.field.name})`,
      );
  }
}

