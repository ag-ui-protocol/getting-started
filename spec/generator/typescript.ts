/**
 * The TypeScript emitter: model in, source text out.
 *
 * No interpretation happens here — the model already resolved composition,
 * requiredness, discriminators and documentation. This file decides TypeScript
 * idiom only: interfaces for objects, a TS enum for EventType (parity with the
 * handwritten SDK the output will one day replace), zod v4 via the `zod/v4`
 * subpath, `.looseObject` because the implementation layer is tolerant while
 * the spec stays strict, and `any` for the arbitrary-JSON positions.
 *
 * If a field's meaning ever appears in this file, it has escaped the schema.
 */

import type {
  Definition,
  Field,
  ObjectDefinition,
  ProtocolModel,
  TypeExpr,
} from "./ir";
import { assertTableKeys } from "./tables";

/** The one enum emitted as a TS enum rather than a literal union. */
const TS_ENUM = "EventType";

function banner(model: ProtocolModel): string {
  return [
    "// @generated by spec/generator — DO NOT EDIT.",
    `// Source: ${model.schemaId}`,
    "// Regenerate: pnpm --filter @ag-ui/spec generate",
    "/* eslint-disable */",
    "",
  ].join("\n");
}

/** Wraps a description into a JSDoc block at a readable width. */
function jsdoc(
  description: string,
  extraTags: string[] = [],
  indent = "",
): string {
  const words = description.split(" ");
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    const candidate = current === "" ? word : `${current} ${word}`;
    if (candidate.length > 76 - indent.length && current !== "") {
      lines.push(current);
      current = word;
    } else {
      current = candidate;
    }
  }
  if (current !== "") lines.push(current);
  const body = [...lines, ...extraTags];
  return [
    `${indent}/**`,
    ...body.map((line) => `${indent} * ${line}`),
    `${indent} */`,
  ].join("\n");
}

/** Renders a TypeExpr as a TypeScript type. */
function tsType(type: TypeExpr): string {
  switch (type.kind) {
    case "string":
      return "string";
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "literal":
      return type.enumRef === TS_ENUM
        ? `${TS_ENUM}.${type.value}`
        : JSON.stringify(type.value);
    case "any":
      return "any";
    case "openMap":
      return "Record<string, any>";
    case "stringEnum":
      return type.values.map((value) => JSON.stringify(value)).join(" | ");
    case "ref":
      return type.name;
    case "array": {
      const items = tsType(type.items);
      const needsParens =
        type.items.kind === "union" || type.items.kind === "stringEnum";
      return needsParens ? `(${items})[]` : `${items}[]`;
    }
    case "union":
      return type.members.map(tsType).join(" | ");
  }
}

function fieldTags(field: Field): string[] {
  const tags: string[] = [];
  if (field.defaultValue !== undefined) {
    tags.push(`@default ${JSON.stringify(field.defaultValue)}`);
  }
  if (field.contentEncoding !== undefined) {
    tags.push(`@contentEncoding ${field.contentEncoding}`);
  }
  return tags;
}

// Object shapes are emitted as type aliases, not interfaces, deliberately:
// an object-literal type gets an implicit index signature, so a concrete
// event stays assignable to open shapes like the SDK's historic BaseEvent
// (base fields plus `[key: string]: unknown`), exactly as zod-inferred alias
// types always were. An interface never satisfies an index signature, and
// nothing generated should be augmentable by declaration merging anyway.
function emitObjectType(definition: ObjectDefinition): string {
  let materialised = false;
  const fields = definition.fields
    .map((field) => {
      const base =
        field.type.kind === "array" && field.type.itemsDescription !== undefined
          ? `${field.description} Each item: ${field.type.itemsDescription}`
          : field.description;
      // Descriptions are copied from the schema, which describes the WIRE. For
      // a materialised field that leaves the doc contradicting the type it sits
      // on — the schema says "Absent means none", and absent is exactly what
      // this type can no longer express — so the divergence is stated here
      // rather than left for a reader to trip over.
      const materialise = ABSENT_MEANS_EMPTY.has(`${definition.name}.${field.name}`);
      if (materialise) materialised = true;
      const description = materialise
        ? `${base} Optional on the wire; the TypeScript SDK materialises an absent one as an empty list, so this type requires it.`
        : base;
      const doc = jsdoc(description, fieldTags(field), "  ");
      const optional = field.required || materialise ? "" : "?";
      return `${doc}\n  ${field.name}${optional}: ${tsType(field.type)};`;
    })
    .join("\n");
  // Same reason, one level up: a description that enumerates which fields are
  // required is true of the schema and false of this type once anything here
  // is materialised.
  const description = materialised
    ? `${definition.description} Requiredness above describes the wire; this TypeScript type additionally requires every field the SDK materialises.`
    : definition.description;
  return `${jsdoc(description)}\nexport type ${definition.name} = {\n${fields}\n};`;
}

function emitTypeDefinition(definition: Definition): string {
  switch (definition.kind) {
    case "object":
      return emitObjectType(definition);
    case "union":
      return `${jsdoc(definition.description)}\nexport type ${definition.name} =\n${definition.members
        .map((member) => `  | ${member}`)
        .join("\n")};`;
    case "enum": {
      if (definition.name === TS_ENUM) {
        const members = definition.values
          .map((value) => `  ${value} = ${JSON.stringify(value)},`)
          .join("\n");
        return `${jsdoc(definition.description)}\nexport enum ${definition.name} {\n${members}\n}`;
      }
      const members = definition.values.map((value) => JSON.stringify(value));
      return `${jsdoc(definition.description)}\nexport type ${definition.name} = ${members.join(" | ")};`;
    }
    case "alias":
      return `${jsdoc(definition.description)}\nexport type ${definition.name} = ${tsType(definition.type)};`;
  }
}

export function emitTypes(model: ProtocolModel): string {
  // The mixin shapes come last: every event and message flattens them in, but
  // consumers also need the shared shapes themselves (BaseEvent is the "fields
  // every event carries" type the SDKs are written against).
  return [
    banner(model),
    ...model.definitions.map(emitTypeDefinition),
    ...model.mixinShapes.map(emitTypeDefinition),
    "",
  ].join("\n\n");
}

/** Renders a TypeExpr as a zod v4 expression. */
/**
 * Optional fields whose contract reads an explicit null as absent, rather than
 * as the null value itself. Only RunAgentInput.state: absent means "no state"
 * and a bare null says the same thing, which every consumer already collapses
 * and .NET's representation cannot tell apart. Nulls INSIDE the value are data
 * and survive.
 *
 * Distinct from the legacy event-level null tolerances, which are producer bugs
 * shimmed at the compatibility boundary and listed in DEPRECATIONS.md. This one
 * is the contract, and it applies where no boundary exists: a server parsing a
 * request body.
 */
const NULL_MEANS_ABSENT = new Set(["RunAgentInput.state"]);

/**
 * Optional list fields the TypeScript SDK materialises as an empty list rather
 * than leaving absent.
 *
 * The schema leaves these optional deliberately — "an absent key and an empty
 * array mean the same thing, so requiring them would catch nothing a producer
 * could get wrong" — and that stays true of the wire, where a producer may omit
 * them freely. It is a poor bargain for a consumer, though: every reader would
 * have to narrow a value that has only one meaning, and nine integration
 * packages stopped compiling for want of it.
 *
 * So the SDK presents the one form every layer already accepts. The protobuf
 * decoder already decodes these two fields to present-empty, since the wire
 * cannot tell an absent repeated field from an empty one — though that is a
 * per-field choice there rather than a rule: the same decoder deletes an empty
 * `usage` on RUN_FINISHED, going the other way under the same constraint. So
 * this aligns the JSON path with the binary one for TOOLS AND CONTEXT, and
 * only in TypeScript: Python and .NET keep both fields optional, because the
 * marker lives in this emitter alone.
 *
 * Absent in, empty out — no meaning is invented, because absent and empty were
 * never different meanings. The default is a FACTORY, not a literal: zod stores
 * a literal in the schema and hands the same instance to every parse, so one
 * consumer's push would leak into every later parse in the process.
 */
const ABSENT_MEANS_EMPTY = new Set([
  "RunAgentInput.tools",
  "RunAgentInput.context",
]);

function zodType(type: TypeExpr): string {
  switch (type.kind) {
    case "string": {
      let expr = "z.string()";
      if (type.pattern !== undefined) {
        expr += `.regex(new RegExp(${JSON.stringify(type.pattern)}))`;
      }
      return expr;
    }
    case "integer": {
      let expr = "z.int()";
      if (type.minimum !== undefined) expr += `.min(${type.minimum})`;
      if (type.maximum !== undefined) expr += `.max(${type.maximum})`;
      return expr;
    }
    case "boolean":
      return "z.boolean()";
    case "literal":
      return type.enumRef === TS_ENUM
        ? `z.literal(${TS_ENUM}.${type.value})`
        : `z.literal(${JSON.stringify(type.value)})`;
    case "any":
      return "z.any()";
    case "openMap":
      // Not z.record: its key schema rejects prototype-named keys such as
      // "constructor", which are valid JSON the spec accepts. z.custom checks
      // "plain object" and passes the value through untouched.
      return (
        "z.custom<Record<string, any>>(" +
        '(value) => typeof value === "object" && value !== null && !Array.isArray(value)' +
        ")"
      );
    case "stringEnum":
      return `z.enum([${type.values.map((value) => JSON.stringify(value)).join(", ")}])`;
    case "ref":
      return `${type.name}Schema`;
    case "array": {
      let expr = `z.array(${zodType(type.items)})`;
      if (type.minItems !== undefined) expr += `.min(${type.minItems})`;
      return expr;
    }
    case "union":
      return `z.union([${type.members.map(zodType).join(", ")}])`;
  }
}

function emitSchemaDefinition(
  definition: Definition,
  anyAliases: Set<string>,
  isMixin = false,
): string {
  const doc = jsdoc(definition.description);
  switch (definition.kind) {
    case "object": {
      const fields = definition.fields
        .map((field) => {
          // zod treats a property whose schema accepts undefined as an
          // optional key, so a required arbitrary-JSON field needs an explicit
          // presence check or a missing key would parse.
          const acceptsUndefined =
            field.type.kind === "any" ||
            (field.type.kind === "ref" && anyAliases.has(field.type.name));
          const presence =
            field.required && acceptsUndefined
              ? ".refine((value) => value !== undefined)"
              : "";
          const optional = field.required
            ? ""
            : ABSENT_MEANS_EMPTY.has(`${definition.name}.${field.name}`)
              ? ".default(() => [])"
              : ".optional()";
          // A field the protocol reads as absent when it arrives as null: the
          // coercion belongs with the validator because a server parsing a
          // request body has no middleware in front of it. It sits INSIDE the
          // optional, so an absent key stays absent rather than materialising
          // as an undefined-valued one.
          const nullMeansAbsent = NULL_MEANS_ABSENT.has(
            `${definition.name}.${field.name}`,
          )
            ? ".nullable().transform((value) => value ?? undefined)"
            : "";
          return `  ${field.name}: ${zodType(field.type)}${presence}${nullMeansAbsent}${optional},`;
        })
        .join("\n");
      // looseObject on purpose: the spec is strict, the implementation is
      // tolerant, and the middleware that warns and strips needs the unknown
      // keys to survive the parse.
      //
      // Which is why looseObject cannot itself say whether the SPEC leaves an
      // object open — every object is loose here. The few the spec really does
      // leave open are marked, so the stripping stage can tell "tolerated until
      // enforcement" from "allowed to stay". Today that is the RFC 6902
      // operations, which the RFC requires to ignore members they do not define
      // rather than reject them. Mixin shapes reach this branch too, via the
      // separate emit pass below, which is what `isMixin` is for: a mixin is
      // not a value on the wire, so saying the spec leaves IT open states
      // nothing. (It could not mislead the stripper either — mixin fields are
      // flattened into each composing definition, so nothing walks the mixin's
      // own schema — but a mark that means nothing is worth not emitting.)
      const openMark =
        definition.closed || isMixin ? "" : ".meta({ specOpen: true })";
      return `${doc}\nexport const ${definition.name}Schema = z.looseObject({\n${fields}\n})${openMark};`;
    }
    case "union": {
      const members = definition.members.map((member) => `${member}Schema`);
      const expr =
        definition.discriminator !== undefined
          ? `z.discriminatedUnion(${JSON.stringify(definition.discriminator)}, [\n${members
              .map((member) => `  ${member},`)
              .join("\n")}\n])`
          : `z.union([\n${members.map((member) => `  ${member},`).join("\n")}\n])`;
      return `${doc}\nexport const ${definition.name}Schema = ${expr};`;
    }
    case "enum": {
      const expr =
        definition.name === TS_ENUM
          ? `z.enum(${TS_ENUM})`
          : `z.enum([${definition.values.map((value) => JSON.stringify(value)).join(", ")}])`;
      return `${doc}\nexport const ${definition.name}Schema = ${expr};`;
    }
    case "alias":
      return `${doc}\nexport const ${definition.name}Schema = ${zodType(definition.type)};`;
  }
}

export function emitSchemas(model: ProtocolModel): string {
  const usesEnum = model.definitions.some(
    (definition) => definition.kind === "enum" && definition.name === TS_ENUM,
  );
  const imports = [
    `import { z } from "zod/v4";`,
    ...(usesEnum ? [`import { ${TS_ENUM} } from "./types";`] : []),
  ].join("\n");
  // Transitive: an alias of an alias of any accepts undefined just the same.
  const anyAliases = new Set<string>();
  let grew = true;
  while (grew) {
    grew = false;
    for (const definition of model.definitions) {
      if (definition.kind !== "alias" || anyAliases.has(definition.name))
        continue;
      const target = definition.type;
      if (
        target.kind === "any" ||
        (target.kind === "ref" && anyAliases.has(target.name))
      ) {
        anyAliases.add(definition.name);
        grew = true;
      }
    }
  }
  return [
    banner(model),
    imports,
    ...model.definitions.map((definition) =>
      emitSchemaDefinition(definition, anyAliases),
    ),
    // The mixin shapes, emitted last so everything they reference exists. Never
    // marked spec-open — see the `isMixin` branch above for why: a mixin is not
    // a value, so the mark would say nothing about anything.
    ...model.mixinShapes.map((definition) =>
      emitSchemaDefinition(definition, anyAliases, true),
    ),
    "",
  ].join("\n\n");
}

export function emitVersion(model: ProtocolModel): string {
  const doc = jsdoc(
    `The protocol version this code was generated from: the version segment of the schema's $id (${model.schemaId}). Never typed by a human.`,
  );
  return [
    banner(model),
    `${doc}\nexport const PROTOCOL_VERSION = ${JSON.stringify(model.version)};`,
    "",
  ].join("\n\n");
}

export interface GeneratedFile {
  name: string;
  content: string;
}

export function emitTypeScript(model: ProtocolModel): GeneratedFile[] {
  assertTableKeys("TS_ENUM", [TS_ENUM], model);
  assertTableKeys("NULL_MEANS_ABSENT", NULL_MEANS_ABSENT, model);
  assertTableKeys("ABSENT_MEANS_EMPTY", ABSENT_MEANS_EMPTY, model);
  return [
    { name: "types.ts", content: emitTypes(model) },
    { name: "schemas.ts", content: emitSchemas(model) },
    { name: "version.ts", content: emitVersion(model) },
  ];
}
