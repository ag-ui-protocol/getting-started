/**
 * The Python emitter: model in, pydantic source out.
 *
 * Python idiom only — the model already resolved everything. Design mirrors
 * the handwritten SDK where the two agree (snake_case fields behind to_camel
 * aliases, EventType as a str Enum, Literal discriminators, Annotated
 * discriminated unions) and follows the schema where they differ: required
 * fields have no defaults, explicit null is rejected wherever the schema has
 * no null, and — the reason this target exists — the generated base model
 * omits valueless fields when serializing, by default, instead of each model
 * remembering to.
 *
 * If a field's meaning ever appears in this file, it has escaped the schema.
 */

